#!/usr/bin/env bash
# DeAI - one-time setup on an HPC login node, for GPU nodes without internet.
#
# Run on the LOGIN node (it has internet); everything a job needs ends up on disk:
#   1. .venv with the pinned packages (requirements.txt, CUDA 12.8 torch)
#   2. the SlopBench corpus (data/slopbench) and data/passages.parquet
#   3. every Hugging Face model the pipeline loads, in $HF_HOME, checked offline
#   4. hpc_env.sh, which jobs source to point at that cache with the hub offline
#
# Usage:  scripts/hpc_setup.sh [download_models.py args]
#   HF_HOME=/scratch/$USER/hf scripts/hpc_setup.sh       # cache outside $HOME (recommended: ~12 GB)
#   PYTHON=python3.12 scripts/hpc_setup.sh               # interpreter to build the venv with
#   scripts/hpc_setup.sh --base Qwen/Qwen2.5-1.5B-Instruct   # also fetch another policy base
#
# Load your cluster's Python 3.12 module first if `python3.12` isn't on PATH
# (e.g. `module load python/3.12`). Rerunning is safe: finished steps are skipped
# or are no-ops. Gated models need `huggingface-cli login` (or HF_TOKEN) first.
#
# In a job script:
#   source /path/to/DeAI-project/hpc_env.sh
#   python -m deai.train_dpo --run <name> --reward quick --rounds 3

set -euo pipefail
cd "$(dirname "$0")/.."
ROOT="$PWD"

PYTHON="${PYTHON:-python3.12}"
export HF_HOME="${HF_HOME:-$HOME/.cache/huggingface}"
export PYTHONIOENCODING=utf-8

step() { printf '\n=== %s ===\n' "$*"; }

# --- 1. venv --------------------------------------------------------------------
step "1/4 Python environment (.venv)"
if [[ ! -x .venv/bin/python ]]; then
    command -v "$PYTHON" >/dev/null || { echo "Error: $PYTHON not found; load a Python 3.12 module or set PYTHON." >&2; exit 1; }
    "$PYTHON" -m venv .venv
fi
PY="$ROOT/.venv/bin/python"
"$PY" -c 'import sys; assert sys.version_info[:2] == (3, 12), f"need Python 3.12, venv has {sys.version}"'
"$PY" -m pip install --upgrade pip -q
"$PY" -m pip install -r requirements.txt
"$PY" -m pip install -e . --no-deps -q
# Linear-attention kernels for Qwen3.5 bases (Qwen/Qwen3.5-9B, ...). Without them transformers
# falls back to a correct but much slower PyTorch path; Qwen3 bases don't use them. Linux only.
# The constraint keeps torch/transformers at the pinned versions.
"$PY" -m pip install -c requirements.txt flash-linear-attention==0.6.0 \
    || echo "Warning: flash-linear-attention failed to install; Qwen3.5 bases will be slow." >&2
# causal-conv1d has no prebuilt wheel for every torch, so it may compile, which needs an
# nvcc of torch's CUDA major version (torch refuses to build across majors). Optional:
# without it only the short depthwise convolutions use the PyTorch fallback.
if "$PY" -c 'import causal_conv1d' 2>/dev/null; then
    echo "causal-conv1d already installed"
else
    TORCH_CUDA=$("$PY" -c 'import torch; print(torch.version.cuda or "")')
    NVCC_CUDA=$(nvcc --version 2>/dev/null | sed -n 's/.*release \([0-9.]*\).*/\1/p')
    if [[ -n "$NVCC_CUDA" && "${NVCC_CUDA%%.*}" == "${TORCH_CUDA%%.*}" ]]; then
        export CUDA_HOME="${CUDA_HOME:-$(dirname "$(dirname "$(command -v nvcc)")")}"
        "$PY" -m pip install -q ninja
        MAX_JOBS="${MAX_JOBS:-4}" "$PY" -m pip install -c requirements.txt --no-build-isolation causal-conv1d==1.7.0 \
            || echo "Warning: causal-conv1d failed to build; skipped (optional)." >&2
    else
        echo "Warning: skipping causal-conv1d (optional): it needs nvcc for CUDA ${TORCH_CUDA%%.*}.x to match torch" \
             "(CUDA $TORCH_CUDA), found ${NVCC_CUDA:-no nvcc}. Load one first, e.g. \`module avail cuda\`," \
             "\`module load cuda/${TORCH_CUDA}\`, then rerun this script." >&2
    fi
fi

# --- 2. data --------------------------------------------------------------------
step "2/4 SlopBench corpus and passages"
if compgen -G "data/slopbench/*.jsonl" >/dev/null; then
    echo "data/slopbench already present"
else
    "$PY" scripts/fetch_slopbench.py
fi
if [[ -f data/passages.parquet ]]; then
    echo "data/passages.parquet already present"
else
    "$PY" scripts/build_data.py
fi

# --- 3. models ------------------------------------------------------------------
step "3/4 Hugging Face models -> $HF_HOME"
mkdir -p "$HF_HOME"
"$PY" scripts/download_models.py "$@"

# --- 4. job environment ---------------------------------------------------------
step "4/4 hpc_env.sh"
cat > hpc_env.sh <<EOF
# Generated by scripts/hpc_setup.sh on $(date -I). Source it in job scripts:
#   source $ROOT/hpc_env.sh
cd "$ROOT"
source "$ROOT/.venv/bin/activate"
export HF_HOME="$HF_HOME"
# GPU nodes have no internet: never try the hub, read only the cache.
export HF_HUB_OFFLINE=1
export TRANSFORMERS_OFFLINE=1
export HF_DATASETS_OFFLINE=1
export HF_HUB_DISABLE_TELEMETRY=1
export PYTHONIOENCODING=utf-8
EOF
echo "wrote $ROOT/hpc_env.sh"

cat <<EOF

Setup done. In a job (or an interactive GPU session):
  source $ROOT/hpc_env.sh
  python scripts/download_models.py --check        # optional: confirm offline loading on the node
  python -m deai.train_dpo --run smoke --reward quick --rounds 1 --train-limit 8 --eval-limit 8 --n 4
EOF
